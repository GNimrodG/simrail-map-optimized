import { type FunctionComponent, useEffect, useState } from "react";
import { LayerGroup, useMap } from "react-leaflet";

import CrossingSignsData from "../../assets/crossing-signs.json";
import CrossingsData from "../../assets/crossings.json";
import { Crossing, CrossingSign } from "../../utils/types";
import CrossingMarker from "../markers/crossings/CrossingMarker";
import CrossingSignMarker from "../markers/crossings/CrossingSignMarker";

const BUFFER_FACTOR = 0.2; // 20% buffer for map bounds
const MIN_ZOOM = 13; // Minimum zoom level to show the crossings
const LABEL_ZOOM = 15; // the kilometres under the icons from here
const SIGN_ZOOM = 14; // the signs before the crossings from here

// The level crossings of the game's map and the W6b signs before them, generated by
// .claude/skills/extract-game-map-data/scripts/extract_crossings.py
const CROSSINGS = CrossingsData as Crossing[];
const SIGNS = CrossingSignsData as CrossingSign[];

function getVisible<T extends { lat: number; lon: number }>(map: L.Map, items: T[], minZoom: number): T[] {
  try {
    if (map.getZoom() < minZoom) {
      return [];
    }

    const bounds = map.getBounds().pad(BUFFER_FACTOR);
    return items.filter((item) => bounds.contains([item.lat, item.lon]));
  } catch (e) {
    console.error("Failed to filter visible crossings: ", e);
    return [];
  }
}

const CrossingsLayer: FunctionComponent = () => {
  const map = useMap();
  const [visibleCrossings, setVisibleCrossings] = useState<Crossing[]>(() => getVisible(map, CROSSINGS, MIN_ZOOM));
  const [visibleSigns, setVisibleSigns] = useState<CrossingSign[]>(() => getVisible(map, SIGNS, SIGN_ZOOM));
  const [showLabels, setShowLabels] = useState(() => map.getZoom() >= LABEL_ZOOM);

  useEffect(() => {
    // the data is local, so the crossings in view are updated right when the map stops moving
    const update = () => {
      setVisibleCrossings(getVisible(map, CROSSINGS, MIN_ZOOM));
      setVisibleSigns(getVisible(map, SIGNS, SIGN_ZOOM));
      setShowLabels(map.getZoom() >= LABEL_ZOOM);
    };

    map.on("moveend zoomend resize", update);
    update();

    return () => {
      map.off("moveend zoomend resize", update);
    };
  }, [map]);

  if (!visibleCrossings.length && !visibleSigns.length) {
    return null;
  }

  return (
    <LayerGroup pane="crossingsPane">
      {visibleCrossings.map((crossing) => (
        <CrossingMarker key={crossing.id} crossing={crossing} showLabel={showLabels} />
      ))}
      {visibleSigns.map((sign) => (
        <CrossingSignMarker key={sign.id} sign={sign} />
      ))}
    </LayerGroup>
  );
};

export default CrossingsLayer;
